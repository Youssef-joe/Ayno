#!/bin/bash
# Comprehensive Benchmark Runner for Polyglot Realtime Engine
# Professional-grade performance validation suite

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"
RESULTS_DIR="$SCRIPT_DIR/results"
TIMESTAMP=$(date +%Y%m%d_%H%M%S)

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Configuration
export BASE_URL="${BASE_URL:-http://localhost:4000}"
export WS_URL="${WS_URL:-ws://localhost:4000/socket/websocket}"
export API_KEY="${API_KEY:-valid_key_demo-app}"
export APP_ID="${APP_ID:-demo-app}"

# Create results directory
mkdir -p "$RESULTS_DIR"

log_info() {
    echo -e "${BLUE}[INFO]${NC} $1"
}

log_success() {
    echo -e "${GREEN}[SUCCESS]${NC} $1"
}

log_warning() {
    echo -e "${YELLOW}[WARNING]${NC} $1"
}

log_error() {
    echo -e "${RED}[ERROR]${NC} $1"
}

check_service() {
    local url=$1
    local name=$2
    log_info "Checking $name at $url..."
    
    if curl -s --max-time 5 "$url" > /dev/null 2>&1; then
        log_success "$name is running"
        return 0
    else
        log_error "$name is not responding at $url"
        return 1
    fi
}

run_k6_test() {
    local test_file=$1
    local test_name=$(basename "$test_file" .js)
    local result_file="$RESULTS_DIR/k6_${test_name}_${TIMESTAMP}.json"
    
    log_info "Running k6 test: $test_name"
    
    if command -v k6 &> /dev/null; then
        k6 run --out json="$result_file" "$test_file" 2>&1 | tee "$RESULTS_DIR/k6_${test_name}_${TIMESTAMP}.log"
        log_success "k6 test completed: $test_name"
    else
        log_warning "k6 not installed. Install with: brew install k6 or see https://k6.io/docs/getting-started/installation/"
        return 1
    fi
}

run_wrk_test() {
    local duration=${1:-30s}
    local threads=${2:-2}
    local connections=${3:-100}
    local result_file="$RESULTS_DIR/wrk_${TIMESTAMP}.txt"
    
    log_info "Running wrk benchmark ($duration, $threads threads, $connections connections)"
    
    if command -v wrk &> /dev/null; then
        wrk -t$threads -c$connections -d$duration -s "$SCRIPT_DIR/wrk/throughput.lua" "$BASE_URL" 2>&1 | tee "$result_file"
        log_success "wrk benchmark completed"
    else
        log_warning "wrk not installed. Install with: brew install wrk or apt-get install wrk"
        return 1
    fi
}

run_legacy_benchmarks() {
    log_info "Running legacy Go benchmarks..."
    
    if [ -f "$SCRIPT_DIR/simple_benchmark.go" ]; then
        cd "$SCRIPT_DIR"
        go run simple_benchmark.go 2>&1 | tee "$RESULTS_DIR/go_simple_${TIMESTAMP}.log"
        log_success "Go simple benchmark completed"
    fi
    
    if [ -f "$SCRIPT_DIR/latency_bench.go" ]; then
        cd "$SCRIPT_DIR"
        # Note: This requires the services to be running
        # go run latency_bench.go 2>&1 | tee "$RESULTS_DIR/go_latency_${TIMESTAMP}.log"
        log_info "Skipping latency_bench.go (requires running services)"
    fi
}

generate_report() {
    local report_file="$RESULTS_DIR/benchmark_report_${TIMESTAMP}.md"
    
    log_info "Generating benchmark report..."
    
    cat > "$report_file" << EOF
# Polyglot Benchmark Report

**Date:** $(date)
**Base URL:** $BASE_URL
**WebSocket URL:** $WS_URL

## Test Summary

### k6 Tests
EOF

    # List k6 results
    if ls "$RESULTS_DIR"/k6_*_${TIMESTAMP}.log 1> /dev/null 2>&1; then
        for log in "$RESULTS_DIR"/k6_*_${TIMESTAMP}.log; do
            echo "" >> "$report_file"
            echo "#### $(basename "$log")" >> "$report_file"
            echo '```' >> "$report_file"
            tail -50 "$log" >> "$report_file"
            echo '```' >> "$report_file"
        done
    else
        echo "No k6 tests executed" >> "$report_file"
    fi

    cat >> "$report_file" << EOF

### wrk Tests
EOF

    if ls "$RESULTS_DIR"/wrk_${TIMESTAMP}.txt 1> /dev/null 2>&1; then
        for txt in "$RESULTS_DIR"/wrk_${TIMESTAMP}.txt; do
            echo "" >> "$report_file"
            echo '```' >> "$report_file"
            cat "$txt" >> "$report_file"
            echo '```' >> "$report_file"
        done
    else
        echo "No wrk tests executed" >> "$report_file"
    fi

    cat >> "$report_file" << EOF

## Performance Metrics

| Metric | Target | Actual | Status |
|--------|--------|--------|--------|
| P95 Latency | <100ms | - | - |
| Error Rate | <1% | - | - |
| Throughput | >10k req/s | - | - |

## Recommendations

- Review P95 and P99 latencies for SLA compliance
- Check error rates under stress conditions
- Monitor memory usage during soak tests
- Validate circuit breaker behavior under failure scenarios

---
*Generated by Polyglot Benchmark Suite*
EOF

    log_success "Report generated: $report_file"
}

run_chaos_test() {
    log_info "Running chaos engineering tests..."
    
    # Simulate service failures
    log_warning "Chaos tests require manual intervention or dedicated tooling"
    log_info "See $SCRIPT_DIR/chaos/README.md for chaos engineering scenarios"
}

# Main execution
main() {
    echo "============================================================"
    echo "  Polyglot Realtime Engine - Professional Benchmark Suite"
    echo "============================================================"
    echo ""
    
    # Check prerequisites
    log_info "Checking service availability..."
    
    SERVICES_OK=true
    check_service "$BASE_URL/health" "Elixir Gateway" || SERVICES_OK=false
    check_service "http://localhost:8080/health" "Go Processor" || SERVICES_OK=false
    
    if [ "$SERVICES_OK" = false ]; then
        log_warning "Some services are not running. Starting in Docker..."
        log_info "Run: docker-compose up -d"
        # Don't fail, allow benchmarks that don't need all services
    fi
    
    echo ""
    log_info "Starting benchmark suite..."
    echo ""
    
    # Run different test suites based on arguments
    case "${1:-all}" in
        k6)
            run_k6_test "$SCRIPT_DIR/k6/load_test.js"
            ;;
        stress)
            run_k6_test "$SCRIPT_DIR/k6/stress_test.js"
            ;;
        soak)
            run_k6_test "$SCRIPT_DIR/k6/soak_test.js"
            ;;
        wrk)
            run_wrk_test "${2:-30s}" "${3:-2}" "${4:-100}"
            ;;
        legacy)
            run_legacy_benchmarks
            ;;
        chaos)
            run_chaos_test
            ;;
        all)
            log_info "Running full benchmark suite..."
            
            # Quick k6 load test (shorter duration for CI)
            if command -v k6 &> /dev/null; then
                # Override options for quick test
                export K6_DURATION_OVERRIDE="30s"
                run_k6_test "$SCRIPT_DIR/k6/load_test.js" || true
            else
                log_warning "Skipping k6 tests (not installed)"
            fi
            
            # wrk throughput test
            if command -v wrk &> /dev/null; then
                run_wrk_test "10s" "2" "50" || true
            else
                log_warning "Skipping wrk tests (not installed)"
            fi
            
            # Legacy benchmarks
            run_legacy_benchmarks || true
            ;;
        *)
            echo "Usage: $0 {all|k6|stress|soak|wrk|legacy|chaos}"
            echo ""
            echo "Options:"
            echo "  all      - Run all benchmarks (default)"
            echo "  k6       - Run k6 load test"
            echo "  stress   - Run k6 stress test"
            echo "  soak     - Run k6 soak test (35 minutes)"
            echo "  wrk      - Run wrk HTTP benchmark"
            echo "  legacy   - Run legacy Go benchmarks"
            echo "  chaos    - Run chaos engineering tests"
            echo ""
            echo "Environment variables:"
            echo "  BASE_URL   - Gateway URL (default: http://localhost:4000)"
            echo "  WS_URL     - WebSocket URL (default: ws://localhost:4000/socket/websocket)"
            echo "  API_KEY    - API key for authentication"
            exit 1
            ;;
    esac
    
    echo ""
    generate_report
    
    echo ""
    log_success "Benchmark suite completed!"
    echo "Results saved to: $RESULTS_DIR"
}

main "$@"
